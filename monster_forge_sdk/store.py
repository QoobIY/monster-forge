from __future__ import annotations

import hashlib
import json
import os
import re
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from types import MappingProxyType

from ._paths import asset_root
from .cache import ContentCache


class AssetIntegrityError(ValueError):
    """A declared asset changed or its catalog violates the file contract."""


class AssetNotFound(KeyError):
    """The requested identity, role or URI is absent from this asset release."""


@dataclass(frozen=True)
class AssetFile:
    path: str
    sha256: str
    size_bytes: int
    media_type: str

    @property
    def uri(self) -> str:
        return "/media/" + self.path


@dataclass(frozen=True)
class Asset:
    id: str
    kind: str
    title: str
    revision: int
    group: str
    tags: tuple[str, ...]
    files: Mapping[str, AssetFile]


class AssetStore:
    """Resolve pinned files from a BHM checkout or a mounted asset release.

    Construct once during loading, before rendering frames. Explicit IDs and
    legacy MOM /media URIs resolve to the same hash-checked BHM files. Nothing
    is generated by consumers, and no animation solver is imported. An optional
    local content cache avoids reading a mounted release again on warm launches.
    """

    def __init__(self, root: str | Path | None = None, *, cache_dir: str | Path | None = None,
                 catalog: bytes | None = None) -> None:
        if cache_dir is None:
            cache_dir = os.environ.get("MONSTER_FORGE_CACHE_ROOT")
        self.cache = ContentCache(cache_dir) if cache_dir is not None else None
        self.root = asset_root(root)
        self.media_root = (self.root / "media").resolve()
        manifest = self.media_root / "catalog.json"
        if catalog is None and not manifest.is_file():
            raise FileNotFoundError(
                "Set MONSTER_FORGE_ASSET_ROOT to the Monster Forge asset release"
            )
        payload = manifest.read_bytes() if catalog is None else catalog
        data = json.loads(payload)
        if data.get("schema_version") != 1:
            raise AssetIntegrityError(
                "Unsupported asset catalog schema; migrate the release explicitly"
            )
        self.release_id = hashlib.sha256(payload).hexdigest()
        self._entries = data["assets"]
        self._aliases = data.get("aliases", {})
        self._assets: dict[str, Asset] = {}
        self._uris: dict[str, AssetFile] = {}
        for row in self._entries:
            files = {}
            for role, value in row["files"].items():
                path = value["path"]
                pure = PurePosixPath(path)
                if (
                    not path
                    or pure.is_absolute()
                    or ".." in pure.parts
                    or "\\" in path
                    or path != pure.as_posix()
                ):
                    raise AssetIntegrityError(
                        "Asset paths must be normalized relative media paths"
                    )
                if not re.fullmatch(r"[0-9a-f]{64}", value["sha256"]):
                    raise AssetIntegrityError("Invalid asset sha256")
                if type(value["size_bytes"]) is not int or value["size_bytes"] <= 0:
                    raise AssetIntegrityError("Invalid asset byte size")
                ref = AssetFile(
                    path, value["sha256"], value["size_bytes"], value["media_type"]
                )
                files[role] = ref
                self._register_uri(ref.uri, ref)
            asset = Asset(
                row["id"],
                row["kind"],
                row["title"],
                row["revision"],
                row.get("group", ""),
                tuple(row.get("tags", [])),
                MappingProxyType(files),
            )
            if asset.id in self._assets or asset.kind not in {
                "character",
                "icon",
                "decoration",
                "terrain",
                "font",
                "audio",
            }:
                raise AssetIntegrityError(
                    "Duplicate identity or unsupported asset kind"
                )
            self._assets[asset.id] = asset
            if row.get("source_uri"):
                primary = files.get("image") or files.get("model")
                if primary is not None:
                    self._register_uri(row["source_uri"], primary)

    def _register_uri(self, uri: str, ref: AssetFile) -> None:
        if uri in self._uris and self._uris[uri] != ref:
            raise AssetIntegrityError("Conflicting asset URI aliases")
        self._uris[uri] = ref

    def list(self, kind: str | None = None) -> tuple[Asset, ...]:
        return tuple(a for a in self._assets.values() if kind is None or a.kind == kind)

    def get(self, asset_id: str) -> Asset:
        try:
            return self._assets[self._aliases.get(asset_id, asset_id)]
        except KeyError as error:
            raise AssetNotFound(asset_id) from error

    def file(self, asset_id: str, role: str | None = None) -> AssetFile:
        asset = self.get(asset_id)
        if role is None:
            role = {"font": "font", "audio": "audio", "icon": "image", "terrain": "image"}.get(asset.kind, "model")
        try:
            return asset.files[role]
        except KeyError as error:
            raise AssetNotFound(f"{asset_id}:{role}") from error

    def _path(self, ref: AssetFile) -> Path:
        path = (self.media_root / ref.path).resolve()
        if not path.is_relative_to(self.media_root):
            raise AssetIntegrityError("Asset symlink escapes the media release")
        if not path.is_file():
            raise AssetNotFound(ref.path)
        return path

    def _verify(self, ref: AssetFile, path: Path) -> None:
        if path.stat().st_size != ref.size_bytes:
            raise AssetIntegrityError(f"Asset byte size changed: {ref.path}")
        digest = hashlib.sha256()
        with path.open("rb") as source:
            for chunk in iter(lambda: source.read(1024 * 1024), b""):
                digest.update(chunk)
        if digest.hexdigest() != ref.sha256:
            raise AssetIntegrityError(f"Asset sha256 changed: {ref.path}")

    def path(
        self, asset_id: str, role: str | None = None, *, verify: bool = True
    ) -> Path:
        ref = self.file(asset_id, role)
        return self._resolved_path(ref, verify=verify)

    def _resolved_path(self, ref: AssetFile, *, verify: bool) -> Path:
        if self.cache is not None:
            cached = self.cache.get(ref.sha256, ref.size_bytes, Path(ref.path).suffix)
            if cached is not None:
                return cached
            try:
                return self.cache.import_file(ref.sha256, ref.size_bytes, self._path(ref))
            except ValueError as error:
                raise AssetIntegrityError(f"Asset changed: {ref.path}") from error
        path = self._path(ref)
        if verify:
            self._verify(ref, path)
        return path

    def uri_file(self, uri: str) -> AssetFile:
        """Return pinned metadata without reading file bytes."""
        try:
            return self._uris[uri]
        except KeyError as error:
            raise AssetNotFound(uri) from error

    def resolve_uri(self, uri: str, *, verify: bool = True) -> Path:
        return self._resolved_path(self.uri_file(uri), verify=verify)

    def read(self, asset_id: str, role: str | None = None) -> bytes:
        ref = self.file(asset_id, role)
        payload = self._resolved_path(ref, verify=False).read_bytes()
        if (
            len(payload) != ref.size_bytes
            or hashlib.sha256(payload).hexdigest() != ref.sha256
        ):
            raise AssetIntegrityError(f"Asset changed: {ref.path}")
        return payload

    def catalog(self, kind: str | None = None) -> dict:
        # Return a detached JSON copy; clients cannot mutate the loaded release.
        rows = [row for row in self._entries if kind is None or row["kind"] == kind]
        identities = {row["id"] for row in rows}
        return json.loads(
            json.dumps(
                {"schema_version": 1, "release_id": self.release_id, "assets": rows,
                 "aliases": {old: new for old, new in self._aliases.items() if new in identities}}
            )
        )

    def icon_style(self) -> dict:
        folder = self.root / "styles/icons"
        profile = json.loads((folder / "profile.json").read_bytes())
        if profile.get("schema_version") != 1:
            raise AssetIntegrityError("Unsupported icon style schema")
        for key in ("source", "reference"):
            path = (folder / profile[key]).resolve()
            if not path.is_relative_to(folder.resolve()):
                raise AssetIntegrityError("Style reference escapes its bundle")
            if (
                hashlib.sha256(path.read_bytes()).hexdigest()
                != profile[key + "_sha256"]
            ):
                raise AssetIntegrityError("Preserved icon style reference changed")
        return profile
